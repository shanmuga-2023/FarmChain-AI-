/**
 * Standardized status badge with icon + clean label
 */
export function renderStatusPill(status, customLabel = null) {
  const s = (status || '').toLowerCase();
  
  let type = 'info';
  let iconName = 'clock';
  let label = customLabel || status || 'Pending';

  if (['verified', 'delivered', 'completed', 'active', 'confirmed', 'paid', 'success'].includes(s)) {
    type = 'success';
    iconName = 'checkCircle';
  } else if (['pending', 'processing', 'in_transit', 'intransit', 'shipped'].includes(s)) {
    type = 'warning';
    iconName = s === 'shipped' || s.includes('transit') ? 'delivery' : 'clock';
  } else if (['cancelled', 'failed', 'rejected', 'expired', 'fraud', 'invalid'].includes(s)) {
    type = 'danger';
    iconName = 'xCircle';
  } else if (['available', 'accepted', 'approved'].includes(s)) {
    type = 'primary';
    iconName = 'check';
  }

  return `
    <span class="fc-status-badge fc-status-${type}">
      ${getIcon(iconName, 12, 'fc-status-icon')}
      <span>${label}</span>
    </span>
  `;
}

